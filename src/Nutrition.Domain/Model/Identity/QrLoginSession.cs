namespace Nutrition.Domain.Model.Identity;

public enum QrSessionStatus
{
    Pending = 0,
    Scanned = 1,
    Approved = 2,
    Rejected = 3,
    Consumed = 4,
    Expired = 5
}

/// <summary>
/// Domain entity representing an ephemeral, cryptographically bound cross-device QR login session.
/// Enforces single-use atomic state transitions and time-bounded validity.
/// </summary>
public class QrLoginSession
{
    public string Id { get; set; } = Guid.NewGuid().ToString();

    /// <summary>
    /// High-entropy challenge nonce embedded in the QR code.
    /// </summary>
    public string ChallengeNonce { get; set; } = string.Empty;

    /// <summary>
    /// SHA-256 hash of the desktop browser's ephemeral in-memory secret (BrowserSecretToken).
    /// </summary>
    public string BrowserSecretHash { get; set; } = string.Empty;

    /// <summary>
    /// Ephemeral ECDH P-256 public key generated by Desktop Web.
    /// </summary>
    public string? DesktopPublicKey { get; set; }

    /// <summary>
    /// Ephemeral ECDH P-256 public key sent by Mobile device.
    /// </summary>
    public string? MobilePublicKey { get; set; }

    /// <summary>
    /// AES-256-GCM encrypted approval payload (end-to-end encrypted between Mobile and Desktop).
    /// </summary>
    public string? EncryptedApprovalPayload { get; set; }

    /// <summary>
    /// Visual 2-digit confirmation code displayed on desktop (e.g. "73") to defeat QRLJacking.
    /// </summary>
    public string ConfirmationCode { get; set; } = string.Empty;

    /// <summary>
    /// Visual animal/color glyph pair (e.g. "Emerald Falcon") displayed on desktop.
    /// </summary>
    public string ConfirmationGlyph { get; set; } = string.Empty;

    /// <summary>
    /// Single-use exchange ticket issued upon mobile approval. Valid for 30 seconds.
    /// </summary>
    public string? ExchangeTicket { get; set; }

    /// <summary>
    /// Current lifecycle state.
    /// </summary>
    public QrSessionStatus Status { get; set; } = QrSessionStatus.Pending;

    public DateTime CreatedAtUtc { get; set; } = DateTime.UtcNow;
    public DateTime ExpiresAtUtc { get; set; }

    public string? AuthorizedUserId { get; set; }
    public string? ClientIpAddress { get; set; }
    public string? ClientUserAgent { get; set; }

    public bool IsExpired => DateTime.UtcNow >= ExpiresAtUtc;

    /// <summary>
    /// Factory method to initialize a new pending QR session.
    /// </summary>
    public static QrLoginSession CreateNew(
        string challengeNonce,
        string browserSecretHash,
        string confirmationCode,
        string confirmationGlyph,
        int ttlSeconds = 90,
        string? desktopPublicKey = null,
        string? clientIp = null,
        string? userAgent = null)
    {
        return new QrLoginSession
        {
            Id = Guid.NewGuid().ToString("N"),
            ChallengeNonce = challengeNonce,
            BrowserSecretHash = browserSecretHash,
            ConfirmationCode = confirmationCode,
            ConfirmationGlyph = confirmationGlyph,
            DesktopPublicKey = desktopPublicKey,
            Status = QrSessionStatus.Pending,
            CreatedAtUtc = DateTime.UtcNow,
            ExpiresAtUtc = DateTime.UtcNow.AddSeconds(ttlSeconds),
            ClientIpAddress = clientIp,
            ClientUserAgent = userAgent
        };
    }

    /// <summary>
    /// Advances state to Scanned when a mobile device reads the QR code.
    /// </summary>
    public void MarkScanned(string? mobileIp = null, string? mobileUserAgent = null)
    {
        if (IsExpired)
        {
            Status = QrSessionStatus.Expired;
            throw new InvalidOperationException("Cannot scan an expired QR session.");
        }

        if (Status != QrSessionStatus.Pending)
        {
            throw new InvalidOperationException($"Invalid state transition: Cannot mark session as Scanned from status '{Status}'.");
        }

        Status = QrSessionStatus.Scanned;
    }

    /// <summary>
    /// Authorizes the session from an authenticated mobile device.
    /// Generates a single-use exchange ticket for the desktop client.
    /// </summary>
    public string Approve(string userId, string? mobilePublicKey = null, string? encryptedApprovalPayload = null)
    {
        if (IsExpired)
        {
            Status = QrSessionStatus.Expired;
            throw new InvalidOperationException("Cannot approve an expired QR session.");
        }

        if (Status != QrSessionStatus.Pending && Status != QrSessionStatus.Scanned)
        {
            throw new InvalidOperationException($"Invalid state transition: Cannot approve session with status '{Status}'.");
        }

        AuthorizedUserId = userId;
        MobilePublicKey = mobilePublicKey;
        EncryptedApprovalPayload = encryptedApprovalPayload;
        ExchangeTicket = Guid.NewGuid().ToString("N");
        Status = QrSessionStatus.Approved;

        return ExchangeTicket;
    }

    /// <summary>
    /// Atomically consumes the exchange ticket, transitioning the session to terminal Consumed state.
    /// </summary>
    public void Consume()
    {
        if (IsExpired)
        {
            Status = QrSessionStatus.Expired;
            throw new InvalidOperationException("Cannot consume an expired QR session.");
        }

        if (Status != QrSessionStatus.Approved)
        {
            throw new InvalidOperationException($"Invalid state transition: Cannot consume session with status '{Status}'.");
        }

        Status = QrSessionStatus.Consumed;
    }
}
